# A bot's conversation comment or review body is judged by what it says, not by its format (owner, 2026-11-25: only
# problems a person or bot raised get an answer). A file location or marker is a hint, never the deciding test.
#   finding    raises a problem, question or change request -> bot-comment, followed like other feedback
#   noise      a status category with nothing to answer -> stays in the BOTS line, internal only
#   undecided  neither -> bot-unclassified, an internal triage item that still counts as factory work; never auto-replied
BOT_FOUND = re.compile(r"```suggestion\b|(?:Outside diff range|Potential issue)[^()\n]{0,20}\(\s*[1-9]\d*\s*\)", re.I)
# Status categories: deploy authorization, secrets and infrastructure, releases and previews, reports, summaries, and
# CodeRabbit's pointer to findings that already live in inline threads.
BOT_STATUS = re.compile(
    r"attempting to deploy|authorization required|(?:deploy(?:ment)?|preview) (?:is )?ready|rejected by its provider"
    r"|(?:actions|repository) secrets?\b|rate limit exceeded"
    r"|changeset detected|included in version|release is available|pkg\.pr\.new|open in stackblitz"
    r"|codecov report|\[codecov\]|coverage report|bundle size analysis|codspeed|performance report|review status for"
    r"|\bwalkthrough\b|summari[sz]e[sd]? by|summary by|thanks for using|actionable comments posted", re.I)
BOT_NOTHING = re.compile(r"\blgtm\b|looks good|no (?:actionable |new )?(?:issues|comments|findings|problems)\b|nothing to report"
                         r"|\bapproved?\b|\(\s*0\s*\)|posted: 0\b"
                         r"|thanks? (?:you )?for (?:your|the|this) (?:pr|pull request|contribution)|this is an automated", re.I)
BOT_REQUEST = re.compile(r"\b(?:could|can|would|will) you\b|\bplease\b|\bconsider\b|\bshould(?:n't| not)?\b|\bmust\b"
                         r"|\bneeds? to\b|\bsuggest|\?(?:\s|$)", re.I)
BOT_DEFECT = re.compile(r"\b(?:bug|stale|wrong|incorrect|broken|breaks?|fail(?:s|ed|ing)?|crash\w*|leak\w*|invalid|regression"
                        r"|race|unhandled|throws?|never|missing|instead of|(?:does|is|was|are|wo|ca)n'?t|(?:does|is|are|can) not"
                        r"|cannot|undefined|overflow|typo|vulnerab\w*|unsafe|deadlock|off[- ]by[- ]one)\b", re.I)


def bot_verdict(body):
    """"finding", "noise" or "undecided" for a bot's conversation comment or review body."""
    body = body or ""
    text = pr_signals.finding_text(body)
    if not re.search(r"\w", text):
        return "noise"
    if BOT_FOUND.search(body):
        return "finding"
    asks = BOT_REQUEST.search(text)
    if BOT_STATUS.search(text) or (BOT_NOTHING.search(text) and not asks):
        return "noise"
    if asks or BOT_DEFECT.search(text):
        return "finding"
    # A few words with no problem or request (a label, a heading) leave nothing to judge.
    return "undecided" if len(re.findall(r"\w+", text)) >= 4 else "noise"


def bot_finding(body):
    return bot_verdict(body) == "finding"


_EVENTS = []
_EVENT_SINK = contextvars.ContextVar("followup_event_sink", default=None)
OBSERVATION_WORKERS = 4


def events():
    """Structured observations from the last sweep, including its waiting-issue checks."""
    return copy.deepcopy(_EVENTS)


def event(row, kind, source, detail):
    url = row.get("url") or ""
    source = source or row.get("head_sha") or row.get("merged_at") or row.get("closed_at")
    if not source:
        source = hashlib.sha256(json.dumps(detail, sort_keys=True).encode()).hexdigest()
    key = f"{url}#{kind}#{source}"
    sink = _EVENT_SINK.get()
    sink = _EVENTS if sink is None else sink
    if any(e["key"] == key for e in sink):
        return
    number = row.get("number")
    if number is None and url.rstrip("/").rsplit("/", 1)[-1].isdigit():
        number = int(url.rstrip("/").rsplit("/", 1)[-1])
    sink.append({"key": key, "kind": kind, "url": url, "repo": row.get("repo"), "number": number,
                    "item": row.get("item"), "detail": detail, "at": iso()})


def action(actions, row, text, source=None, kind=None, **detail):
    actions.append(text)
    prefix = text.split(row["url"], 1)[0].strip() if row.get("url") else text.split(":", 1)[0]
    event(row, kind or prefix.lower().replace(" ", "-"), source, {"text": text, **detail})


def persist_events():
    """Flush new keys before advancing the ledger's observation cursors."""
    if not _EVENTS:
        return
    path = ledger.path_from_config("ledger_file").with_name("followup-events.jsonl")
    with ledger.locked():
        seen = set()
        if path.exists():
            for line in path.read_text().splitlines():
                if not line.strip():
                    continue
                try:
                    seen.add(json.loads(line)["key"])
                except (ValueError, KeyError, TypeError):
                    raise ValueError(f"{path.name} contains an incomplete event; repair it before sweeping again") from None
        pending = [e for e in _EVENTS if e["key"] not in seen]
        if not pending:
            return
        with path.open("a", encoding="utf-8") as handle:
            for entry in pending:
                handle.write(json.dumps(entry, ensure_ascii=False) + "\n")
            handle.flush()
            os.fsync(handle.fileno())


def author_login(response):
    return (response.get("author") or {}).get("login", "")


def response_kind(response, mergers=frozenset()):
    author = response.get("author") or {}
    if BOTS.search(author_login(response)) or author.get("type") == "Bot" or author.get("__typename") == "Bot" or author.get("is_bot") or AUTOMATION.search(response.get("body") or ""):
        return "bot"
    if response.get("authorAssociation") in CORE or author_login(response).lower() in mergers:
        return "maintainer"
    return "community"


_MERGERS = {}


def repo_mergers(repo, source=None, consumer=None):
    """Recent merger logins, or None on failure; cache hits are not fresh observations."""
    if repo not in _MERGERS:
        owner, name = repo.split("/", 1)
        query = ("query($owner:String!,$name:String!){repository(owner:$owner,name:$name)"
                 "{pullRequests(last:100,states:MERGED){nodes{mergedBy{login}}}}}")
        row = {"url": f"https://github.com/{repo}", "repo": repo}
        source = source or uuid.uuid4().hex
        try:
            data = gh_json("api", "graphql", "-f", f"query={query}", "-F", f"owner={owner}", "-F", f"name={name}", timeout=GH_READ_TIMEOUT)
            nodes = (((data or {}).get("data") or {}).get("repository") or {}).get("pullRequests", {}).get("nodes")
            if not isinstance(nodes, list) or data.get("errors"):
                raise ValueError("recent mergers missing from the GraphQL response")
            _MERGERS[repo] = frozenset((n.get("mergedBy") or {}).get("login", "").lower() for n in nodes if n.get("mergedBy"))
        except Exception as error:
            event(row, "followup-error", source,
                  {"operation": "repo-mergers", "consumer": consumer,
                   "text": f"recent mergers could not be read: {' '.join(str(error).split())}"})
            return None
        event(row, "repo-mergers-read", source,
              {"operation": "repo-mergers", "text": "recent mergers read successfully", "logins": sorted(_MERGERS[repo])})
    return _MERGERS[repo]


CLA_CHECK = re.compile(r"\bcla(?:\b|assistant)|contributor license|\bdco\b", re.I)
EXTERNAL_CHECK = re.compile(r"^(vercel|netlify|mintlify|pullfrog|cloudflare pages)\b", re.I)


class BaseFailures(set):
    def __init__(self, base=(), others=(), checked=True):
        super().__init__(set(base) | set(others))
        self.base = set(base) if checked else None
        self.others = set(others)


def failing_on_base(repo, base, names, exclude=None):
    """Checks that also fail on the base branch head are the repo's own problem, not the PR's."""
    if not names or not base:
        return BaseFailures(checked=False)
    try:
        runs = (gh_json("api", f"repos/{repo}/commits/{base}/check-runs?per_page=100", timeout=GH_READ_TIMEOUT) or {}).get("check_runs", [])
        statuses = gh_json("api", f"repos/{repo}/commits/{base}/statuses?per_page=100", timeout=GH_READ_TIMEOUT) or []
    except Exception as error:
        event({"url": f"https://github.com/{repo}/pull/{exclude}", "repo": repo, "number": exclude},
              "followup-error", None, {"text": f"base checks could not be read: {' '.join(str(error).split())}"})
        return BaseFailures(checked=False)
    if not isinstance(runs, list) or not isinstance(statuses, list):
        return BaseFailures(checked=False)
    bad = check_runs.failing(runs + statuses, by_workflow=False)
    seen = {check_runs.name(c) for c in runs + statuses}
    unseen = [n for n in names if n not in seen]
    return BaseFailures({n for n in names if n in bad}, failing_on_other_prs(repo, unseen, exclude))


def failing_on_other_prs(repo, names, exclude=None, sample=5, quorum=3):
    """PR-only checks never run on the base branch; they are the repo's own when they fail on every sampled open PR."""
    if not names:
        return set()
    try:
        prs = gh_json("pr", "list", "-R", repo, "--state", "open", "--limit", str(sample + 1),
                      "--json", "number,statusCheckRollup", timeout=GH_READ_TIMEOUT) or []
    except Exception as error:
        event({"url": f"https://github.com/{repo}/pull/{exclude}", "repo": repo, "number": exclude},
              "followup-error", None, {"text": f"other PR checks could not be read: {' '.join(str(error).split())}"})
        return set()
    rollups = [p.get("statusCheckRollup") or [] for p in prs if p.get("number") != exclude][:sample]
    present = [{check_runs.name(c) for c in rollup} for rollup in rollups]
    bad = [check_runs.failing(rollup, by_workflow=False) for rollup in rollups]
    inherited = set()
    for name in names:
        verdicts = [name in failed for seen, failed in zip(present, bad) if name in seen]
        if len(verdicts) >= quorum and all(verdicts):
            inherited.add(name)
    return inherited


def fetch_responses(repo, number, reviews=False):
    endpoint = f"repos/{repo}/pulls/{number}/reviews" if reviews else f"repos/{repo}/issues/{number}/comments"
    return [{**r, "author": r.get("user"), "authorAssociation": r.get("author_association"),
             "createdAt": r.get("created_at"), "submittedAt": r.get("submitted_at")}
            for r in gh_paginate(endpoint + "?per_page=100")]


def observe_repository(rows, me, missing, progress):
    """Keep a repository's PRs serial and buffer events until the coordinator can persist them."""
    observed_events, observations, actions = [], [], []
    token = _EVENT_SINK.set(observed_events)
    try:
        for original in rows:
            r = copy.deepcopy(original)
            if progress:
                progress(f"PR {r['url']}")
            if r["status"] == "closed" and (now() - parse_iso(r["submitted_at"])).days <= REOPEN_WINDOW_DAYS:
                try:
                    if gh_json("pr", "view", r["url"], "--json", "state", timeout=GH_READ_TIMEOUT).get("state") == "OPEN":
                        r.update(status="submitted", closed_at=None)
                        action(actions, r, f"REOPENED {r['url']}: a maintainer reopened it; read the thread and answer any review before new work")
                except Exception as error:
                    action(actions, r, f"FOLLOWUP ERROR {r['url']}: {' '.join(str(error).split())}")
            if r["status"] in ledger.DONE:
                if r["status"] == "closed" and r["url"] in missing:
                    action(actions, r, f"LESSON REQUIRED {r['url']}: read the closing comments and run bin/factory lesson add --pr {r['url']}")
                if r["status"] == "merged" and not r.get("recorded_at"):
                    action(actions, r, f"MERGED {r['url']}: {MERGED_TODO}")
                continue
            try:
                checked = copy.deepcopy(r)
                checked.setdefault("rev", 0)
                check_pr(checked, me, actions)
                observations.append(checked)
            except Exception as error:
                action(actions, r, f"FOLLOWUP ERROR {r['url']}: {' '.join(str(error).split())}")
    finally:
        _EVENT_SINK.reset(token)
    return observations, actions, observed_events


def run(progress=None):
    from factory.util import global_hooks_drift, local_hooks_overrides

    _EVENTS.clear()
    _MERGERS.clear()
    me = CONFIG["github_user"].lower()
    rows = ledger.load()
    observations, actions = [], []
    drift = global_hooks_drift()
    if drift:
        action(actions, {}, f"GLOBAL HOOKS CHANGED: {', '.join(drift)} differ from the baseline; restore them before any commit (L-035)")
    for clone, value in local_hooks_overrides():
        action(actions, {},
            f"HOOKS OVERRIDE {clone}: core.hooksPath={value}; git config --local --unset core.hooksPath, "
            "then recommit unsubmitted items there with git reset --soft HEAD~1 && git commit -C ORIG_HEAD (L-035)"
        )
    try:
        groups = {}
        for row in rows:
            groups.setdefault(row["repo"].lower(), []).append(row)
        missing = {row["url"] for row in ledger.missing_lessons(rows)}
        with ThreadPoolExecutor(max_workers=OBSERVATION_WORKERS) as pool:
            batches = pool.map(lambda group: observe_repository(group, me, missing, progress), groups.values())
            for checked, messages, observed_events in batches:
                observations.extend(checked)
                actions.extend(messages)
                _EVENTS.extend(observed_events)
        # A repository can still owe a read after its last active PR has closed.
        from factory.core.nextaction import merger_error, observations as saved_observations
        attempted = {e.get("repo") for e in _EVENTS if merger_error(e) or e["kind"] == "repo-mergers-read"}
        for entry in saved_observations(False)[0]:
            if merger_error(entry):
                repo = entry["url"].removeprefix("https://github.com/")
                if re.fullmatch(r"[^/]+/[^/]+", repo) and repo not in attempted:
                    attempted.add(repo)
                    if progress:
                        progress(f"Repository {repo}: retry recent mergers")
                    repo_mergers(repo)
    finally:
        persist_events()
        settle_waiting(observations)
        ledger.merge(observations)
    return actions


def settle_waiting(observations):
    """Add "factory" wherever the saved follow-up queue, the same projection bin/factory next dispatches from, still
    owes feedback on the PR, so waiting_on agrees with the queue (vuejs/core #16433 kept a bot finding queued while
    its row said maintainer, 2026-11-25)."""
    from factory.core.nextaction import owed_ci, owed_feedback, owed_triage
    for row in observations:
        parties = row.get("waiting_on")
        if not parties or "factory" in parties:
            continue
        try:
            owed = owed_feedback(row) or owed_ci(row) or owed_triage(row)
        except Exception as error:  # an unreadable queue must not hide work: count it as owed
            event(row, "followup-error", None, {"text": f"follow-up queue could not be read: {' '.join(str(error).split())}"})
            owed = True
        if owed:
            row["waiting_on"] = [p for p in parties if p != "maintainer"] + ["factory"]


WAITING = {"awaiting-maintainer", "issue-only", "ready", "preparing"}


def waiting_issues(runs=None, progress=None):
    """Our own issues whose PR is not out yet: a maintainer reply means submit now, and another
    contributor's PR or a close means the item is gone (L-055)."""
    from factory.util import path_from_config, read_json

    me = CONFIG["github_user"].lower()
    actions = []
    root = runs or path_from_config("runs_dir")
    for path in sorted(root.glob("*/*/item.json")):
        try:
            item = read_json(path, {}) or {}
            if not isinstance(item, dict):
                raise ValueError("item.json must contain an object")
        except (OSError, ValueError) as error:
            action(actions, {"item": str(path.parent)}, f"FOLLOWUP ERROR {path.parent}: {' '.join(str(error).split())}", kind="followup-error")
            continue
        issue, repo = item.get("issue"), item.get("repo")
        if item.get("status") not in WAITING or not isinstance(issue, int) or not repo or item.get("pushed_head"):
            continue
        url = f"https://github.com/{repo}/issues/{issue}"
        row = {"url": url, "repo": repo, "number": issue, "item": str(path.parent)}
        if progress:
            progress(f"Issue {url}")
        try:
            view = gh_json("issue", "view", url, "--json", "state,author", timeout=GH_READ_TIMEOUT) or {}
            if ((view.get("author") or {}).get("login") or "").lower() != me:
                continue
            events = gh_paginate(f"repos/{repo}/issues/{issue}/timeline?per_page=100")
        except Exception as error:
            if "Could not resolve to an issue" in str(error):
                continue  # a discussion number; discussions have no issue timeline
            action(actions, row, f"FOLLOWUP ERROR {url}: {' '.join(str(error).split())}")
            continue
        others = sorted({
            e["source"]["issue"]["number"] for e in events
            if e.get("event") == "cross-referenced" and ((e.get("source") or {}).get("issue") or {}).get("pull_request")
            and ((e["source"]["issue"].get("user") or {}).get("login") or "").lower() != me
        })
        mergers = repo_mergers(repo) or frozenset()
        replies = [e for e in events if e.get("event") == "commented" and response_kind(
            {"author": e.get("actor") or e.get("user"), "authorAssociation": e.get("author_association"), "body": e.get("body")}, mergers) == "maintainer"]
        if view.get("state") == "CLOSED" or others:
            by = f" by PR {', '.join(f'#{n}' for n in others)}" if others else ""
            source = next((e.get("id") for e in reversed(events) if e.get("event") in {"closed", "cross-referenced"}), None)
            action(actions, row, f"ISSUE TAKEN {url}: {'closed' if view.get('state') == 'CLOSED' else 'referenced'}{by}; drop {path.parent.name} unless that PR is ours (L-055)",
                   source=source, pull_requests=others)
        elif replies:
            who = ((replies[-1].get("actor") or replies[-1].get("user") or {}).get("login")) or "[deleted]"
            action(actions, row, f"ISSUE CONFIRMED {url} by {who}: submit {path.parent.name} now, before someone else does (L-055)",
                   source=replies[-1].get("id"), body=replies[-1].get("body") or "")
    persist_events()
    return actions


def bot_comment(actions, row, response):
    verdict = bot_verdict(response.get("body"))
    label = "BOT COMMENT" if verdict == "finding" else "BOT COMMENT TO CLASSIFY"
    text = f"{label} {row['url']} by {author_login(response) or '[deleted]'}: {pr_signals.finding_text(response.get('body') or '')[:160]}"
    action(actions, row, text, source=response.get("id"), kind="bot-comment" if verdict == "finding" else "bot-unclassified",
           body=response.get("body") or "", author_login=author_login(response), state=response.get("state"))


def waiting_on(r, pr):
    """Everyone the open PR waits on, so a red rollup is not read as work for us and one party never hides another:
    "owner" (CLA), "factory" (our CI failure, requested changes, a conflict, or feedback still owed in the saved
    follow-up queue, including CI failures not yet triaged as external) and otherwise "maintainer" (review, approval, or checks needing repository-side authorization)."""
    if r.get("status") in ledger.DONE:
        return None
    parties = []
    if r.get("status") == "awaiting-cla" or r.get("cla_state") in {"failed", "pending", "missing"}:
        parties.append("owner")
    if pr.get("reviewDecision") == "CHANGES_REQUESTED" or pr.get("mergeable") == "CONFLICTING" \
            or r.get("inline_pending") or r.get("bot_pending"):
        parties.append("factory")
    return parties or ["maintainer"]


def check_pr(r, me, actions):
    checked_at = iso(now())
    pr = gh_json("pr", "view", r["url"], "--json", FIELDS, timeout=GH_READ_TIMEOUT)
    number = int(r["url"].rstrip("/").rsplit("/", 1)[1])
    pr["comments"] = fetch_responses(r["repo"], number)
    pr["reviews"] = fetch_responses(r["repo"], number, reviews=True)
    feedback_since = r.get("feedback_since") or r.get("last_check") or r["submitted_at"]
    since = parse_iso(feedback_since)
    checks = pr.get("statusCheckRollup") or []
    failing = sorted(check_runs.failing(checks))
    pending = [c for c in checks if check_runs.pending(c)]
    comments = [c for c in pr.get("comments") or [] if author_login(c).lower() != me]
    reviews = [v for v in pr.get("reviews") or [] if author_login(v).lower() != me and v.get("submittedAt") and v.get("state") != "PENDING"]
    new_comments = [c for c in comments if parse_iso(c["createdAt"]) >= since]
    new_reviews = [v for v in reviews if parse_iso(v["submittedAt"]) >= since]
    scan = uuid.uuid4().hex
    recent_mergers = repo_mergers(r["repo"], source=scan, consumer=r["url"])
    merger_error = f"https://github.com/{r['repo']}#followup-error#{scan}" if recent_mergers is None else None
    mergers = (recent_mergers or frozenset()) | {((pr.get("mergedBy") or {}).get("login") or "").lower()} - {""}
    kinds = {response_kind(x, mergers) for x in comments + reviews}
    responded = {kind: kind in kinds for kind in ("maintainer", "community", "bot")}
    r["responded"] = responded
    # When a maintainer last answered, so the unresponsive test compares answer times, not PR creation times.
    answers = [x.get("submittedAt") or x.get("createdAt") for x in comments + reviews if response_kind(x, mergers) == "maintainer"]
    answers = [stamp for stamp in answers if stamp]
    r["maintainer_answered_at"] = max(answers, key=parse_iso) if answers else None
    head = pr.get("headRefOid")
    if head:
        r["head_sha"] = head
    observed = {**r, "head_sha": head}
    cla_checks = check_runs.latest([c for c in checks if CLA_CHECK.search(check_runs.name(c))])
    cla = sorted({check_runs.name(c) for c in cla_checks if check_runs.outcome(c) not in check_runs.PASSED})
    if cla_checks:
        if any(check_runs.outcome(c) in check_runs.FAILED for c in cla_checks):
            r["cla_state"] = "failed"
        elif cla:
            r["cla_state"] = "pending"
        else:
            r["cla_state"] = "passed"
    elif r.get("cla_state") in {"failed", "pending", "missing"}:
        r["cla_state"] = "missing"
        cla = ["previously unresolved CLA/DCO check is missing"]
    failing = [name for name in failing if not CLA_CHECK.search(name)]
    external = [name for name in failing if EXTERNAL_CHECK.search(name or "")]
    failing = [name for name in failing if name not in external]
    ci_names = set(failing)
    base_failures = failing_on_base(r["repo"], pr.get("baseRefName"), failing, exclude=number)
    inherited = sorted(base_failures)
    failing = [name for name in failing if name not in inherited]
    base_names = getattr(base_failures, "base", base_failures)
    jobs = []
    for check in check_runs.failing_runs(checks):
        name = check_runs.name(check)
        if name not in ci_names:
            continue
        on_base = name in base_names if base_names is not None else None
        job = check_runs.job_detail(check, head, on_base)
        job["failing_on_other_prs"] = name in getattr(base_failures, "others", set())
        jobs.append(job)
    age_days = (now() - parse_iso(r["submitted_at"])).total_seconds() / 86400
    silent_days = CONFIG["limits"].get("silent_days", 7)

    if pr["mergedAt"]:
        r.update(status="merged", merged_at=pr["mergedAt"])
        action(actions, r, f"MERGED {r['url']}: {MERGED_TODO}")
    elif pr["state"] == "CLOSED":
        r.update(status="closed", closed_at=pr.get("closedAt"))
        action(actions, r, f"CLOSED {r['url']}: read why, bin/factory lesson add --pr {r['url']}, then bin/factory clean --prune")
    elif cla:
        r["status"] = "awaiting-cla"
        if r.get("silent"):
            r["silent"] = None
    elif pr["reviewDecision"] == "CHANGES_REQUESTED":
        r["status"] = "changes-requested"
    elif failing:
        r["status"] = "ci-failing"
    elif responded["maintainer"]:
        r["status"] = "in-review"
    elif responded["community"]:
        r["status"] = "community-review"
    elif age_days >= silent_days:
        r["status"] = "silent"
    else:
        r["status"] = "submitted"

    if r["status"] in ("silent", "community-review") and age_days >= silent_days and not responded["maintainer"]:
        if not r.get("silent"):
            r["silent"] = iso()
        if not r.get("lesson"):
            action(actions, observed,
                f"SILENT {r['url']}: no maintainer response in {age_days:.0f} days. Study why (size, timing, review tier, "
                f"missing issue link, repo habits) and record it with bin/factory lesson add --pr {r['url']}; "
                "its silence alone does not stop other submissions"
            )

    if cla:
        text = f"CLA {r['url']}: the owner has to sign it ({', '.join(cla)}); nothing else blocks review"
        actions.append(text)
        owner_action = (f"The owner must resolve the {r['repo']} CLA/DCO at {r['url']} ({', '.join(cla)}); "
                        "review is blocked. Record this action in docs/owner-actions.md.")
        for check in [c for c in cla_checks if check_runs.name(c) in cla] or [{}]:
            event(observed, "cla", check_runs.source_id(check),
                  {"text": text, "cla_state": r["cla_state"], "owner_action": owner_action, "checks": cla})

    if inherited:
        action(actions, observed, f"PRE-EXISTING FAILURES {r['url']}: {', '.join(inherited)} also fail on {pr.get('baseRefName')} or on other open PRs; not caused by the PR; {NO_STATUS_REPLY}",
               jobs=[job for job in jobs if job["name"] in inherited], head_sha=head)
    if external:
        action(actions, observed, f"EXTERNAL CHECKS {r['url']}: {', '.join(external)} — deploy/preview bots that need repo-side authorization or config; nothing to fix in the PR; {NO_STATUS_REPLY}")
    if failing:
        text = f"CI FAILING {r['url']}: {', '.join(failing)} — read the logs, fix on the same branch"
        actions.append(text)
        for job in jobs:
            event(observed, "ci-failing", job["check_id"] or job["run_id"],
                  {"text": text, "jobs": jobs, "head_sha": head, "base": pr.get("baseRefName")})
    if pr["reviewDecision"] == "CHANGES_REQUESTED":
        asks = [v for v in reviews if v.get("state") == "CHANGES_REQUESTED"]
        last_commit = max((parse_iso(c["committedDate"]) for c in pr.get("commits") or [] if c.get("committedDate")), default=None)
        if asks:
            ask = max(asks, key=lambda v: parse_iso(v["submittedAt"]))
            if last_commit is None or last_commit < parse_iso(ask["submittedAt"]):
                action(actions, observed, f"CHANGES REQUESTED {r['url']} by {author_login(ask) or '[deleted]'} ({response_kind(ask, mergers)}) at {ask['submittedAt']}: still unaddressed; "
                       "fix on the same branch, rerun redgreen/slop/gate, push, then reply", source=ask.get("id"))
    if pr.get("mergeable") == "CONFLICTING":
        action(actions, observed, f"CONFLICT {r['url']}: {CONFLICT_REPAIR}")
    bots = []
    for c in new_comments:
        kind = response_kind(c, mergers)
        if kind == "bot" and bot_verdict(c.get("body")) != "noise":
            bot_comment(actions, observed, c)
        elif kind == "bot":
            bots.append(c)
        else:
            action(actions, observed, f"{kind.upper()} COMMENT {r['url']} by {author_login(c) or '[deleted]'}: {(c.get('body') or '').strip()[:160]!r}",
                   source=c.get("id"), body=c.get("body") or "", author_login=author_login(c), merger_error=merger_error)
    for v in new_reviews:
        kind = response_kind(v, mergers)
        if kind == "bot" and bot_verdict(v.get("body")) != "noise":
            bot_comment(actions, observed, v)
        elif kind == "bot":
            bots.append(v)
        else:
            action(actions, observed, f"{kind.upper()} REVIEW {r['url']} {v['state']} by {author_login(v) or '[deleted]'}: {(v.get('body') or '').strip()[:160]!r}",
                   source=v.get("id"), body=v.get("body") or "", state=v["state"],
                   author_login=author_login(v), merger_error=merger_error)
    if bots:
        names = sorted({author_login(b) or "[deleted]" for b in bots}, key=str.lower)
        text = f"BOTS {r['url']}: {len(bots)} comments from {', '.join(names)}"
        actions.append(text)
        for bot in bots:
            event(observed, "bots", bot.get("id"), {"text": text, "body": bot.get("body") or ""})
    if pr["state"] == "OPEN":
        threads = {}
        actions += pr_signals.lines(r, number, pr, lambda x: response_kind(x, mergers),
                                   emit=lambda kind, source, detail: event(observed, kind, source, detail), pending=threads)
        # Only a complete thread read replaces the saved list; a failed read keeps the earlier one.
        if "inline" in threads:
            r["inline_pending"] = threads["inline"]
            r["bot_pending"] = threads["bot"]
    r["checks"] = {"failing": failing, "pending": len(pending), "total": len(checks)}
    r["mergeable"] = pr.get("mergeable")
    r["waiting_on"] = waiting_on(r, pr)
    r["last_check"] = checked_at
    r["feedback_since"] = checked_at if recent_mergers is not None else feedback_since
    event(observed, "feedback-read", scan, {"merger_error": merger_error, "since": feedback_since})
