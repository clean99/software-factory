"""Shared PR outcomes and owner records, with locked field-level updates for concurrent writers."""
import contextlib
import fcntl
import re

from factory.util import CONFIG, iso, parse_iso, path_from_config, read_json, write_json

DONE = {"merged", "closed", "abandoned"}
STATUSES = ("submitted", "in-review", "community-review", "changes-requested", "ci-failing", "awaiting-cla", "silent", "merged", "closed", "abandoned")
OBSERVED_FIELDS = frozenset({"status", "last_check", "feedback_since", "checks", "responded", "maintainer_answered_at", "merged_at",
                             "closed_at", "silent", "cla_state", "head_sha", "inline_pending", "bot_pending", "waiting_on", "mergeable"})


def load():
    return read_json(path_from_config("ledger_file"), [])


def save(rows):
    rows.sort(key=lambda r: r.get("submitted_at") or "", reverse=True)
    write_json(path_from_config("ledger_file"), rows)
    render(rows)


def find(rows, url):
    return next((r for r in rows if r.get("url") == url), None)


def pr_key(repo, url):
    """One identity per pull request, across repository renames and URL spellings."""
    from factory.core.repos import canonical

    tail = url.rstrip("/").rsplit("/", 1)[-1]
    number = int(tail) if tail.isdigit() else url
    return canonical(repo).lower(), number


def opened_on(day, rows=None):
    """Pull requests in other people's repositories first submitted on this Asia/Singapore day, each counted once."""
    from zoneinfo import ZoneInfo

    from factory.core.metrics import ACTIVITY_ZONE

    zone = ZoneInfo(ACTIVITY_ZONE)
    own = CONFIG["github_user"].lower() + "/"
    found = set()
    for row in load() if rows is None else rows:
        url, repo, at = row.get("url"), row.get("repo"), row.get("submitted_at")
        if url and repo and at and not repo.lower().startswith(own) and parse_iso(at).astimezone(zone).date() == day:
            found.add(pr_key(repo, url))
    return found


def opened(rows=None):
    """Pull requests in other people's repositories with their first submission time, each counted once."""
    own = CONFIG["github_user"].lower() + "/"
    found = {}
    for row in load() if rows is None else rows:
        url, repo, at = row.get("url"), row.get("repo"), row.get("submitted_at")
        if url and repo and at and not repo.lower().startswith(own):
            found.setdefault(pr_key(repo, url), parse_iso(at))
    return found


def opened_since(start, rows=None):
    """Pull requests in other people's repositories first submitted at or after start, each once, with that time."""
    return {key: at for key, at in opened(rows).items() if at >= start}


@contextlib.contextmanager
def locked():
    with open(path_from_config("ledger_file").with_suffix(".lock"), "w") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


def upsert(row):
    with locked():
        rows = load()
        existing = find(rows, row["url"])
        if existing:
            existing.update(row)
        else:
            rows.append(row)
        save(rows)
    return row


def update_fields(url, **fields):
    """Patch one row without changing its observation revision."""
    with locked():
        rows = load()
        row = find(rows, url)
        if row is None:
            raise ValueError(f"PR {url} is not in the ledger; repair its row with upsert before updating fields")
        row.update({key: value for key, value in fields.items() if key != "rev"})
        save(rows)
        return row


def merge(checked):
    """Apply observed fields, preserving owner data; equal timestamps require the current row revision."""
    with locked():
        current = load()
        by_url = {r["url"]: r for r in current}
        for observed in checked:
            row = by_url.get(observed["url"])
            if row is None:
                row = {**observed, "rev": 1}
                current.append(row)
                by_url[row["url"]] = row
                continue
            if row.get("status") == "merged" or (row.get("status") == "abandoned" and observed.get("status") not in DONE):
                continue
            stored_at = parse_iso(row["last_check"]) if row.get("last_check") else None
            observed_at = parse_iso(observed["last_check"]) if observed.get("last_check") else None
            if stored_at is not None and (observed_at is None or observed_at < stored_at):
                continue
            if observed_at == stored_at and observed.get("rev", 0) != row.get("rev", 0):
                continue
            row.update({key: value for key, value in observed.items() if key in OBSERVED_FIELDS})
            row["rev"] = row.get("rev", 0) + 1
        save(current)


def render(rows):
    lines = [
        "# PR ledger",
        "",
        "Generated by `bin/factory ledger` from `prs.json`; edit the JSON, not this file.",
        "",
        "| Submitted | Repo | PR | Kind | Status | Responded | Last check | Lesson | Notes |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        responded = ", ".join(kind for kind in ("maintainer", "community", "bot") if (r.get("responded") or {}).get(kind))
        if "responded" not in r:
            responded = "not checked"
        lines.append(
            f"| {(r.get('submitted_at') or '')[:10]} | {r['repo']} | [#{r.get('number', '?')}]({r['url']}) "
            f"| {r.get('kind', 'small')} | {r['status']} | {responded or 'none'} | {(r.get('last_check') or '')[:16]} "
            f"| {r.get('lesson') or ''} | {(r.get('notes') or '').replace('|', '/')[:80]} |"
        )
    path_from_config("ledger_file").with_name("README.md").write_text("\n".join(lines) + "\n")


def lesson_ids():
    path = path_from_config("lessons_file")
    if not path.exists():
        return set()
    return set(re.findall(r"^## (L-\d{3,})", path.read_text(), re.M))


def lesson_covers_close(row, text):
    """A silence lesson predating the close is not a review of the closing feedback."""
    closed = row.get("closed_at")
    if not closed:
        return True
    if row.get("lesson_closed_at") == closed:
        return True
    section = re.search(r"^## " + re.escape(row.get("lesson") or "") + r"\b.*?(?=^## |\Z)", text, re.M | re.S)
    source = re.search(r"^- source: (.+)$", section[0], re.M) if section else None
    # A date shared by several citations is ambiguous; require an explicit closing binding instead.
    dates = re.findall(re.escape(row["url"]) + r"\s+\((\d{4}-\d{2}-\d{2})\)", source[1]) if source else []
    return any(date > closed[:10] for date in dates)


def missing_lessons(rows=None):
    ids = lesson_ids()
    path = path_from_config("lessons_file")
    text = path.read_text() if path.exists() else ""
    return [r for r in (load() if rows is None else rows)
            if (r["status"] == "closed" or r.get("silent")) and
            (r.get("lesson") not in ids or (r["status"] == "closed" and not lesson_covers_close(r, text)))]


def add_lesson(title, rule, scope, source, enforced_by, status="active", pr=None):
    path = path_from_config("lessons_file")
    text = path.read_text() if path.exists() else "# Lessons\n"
    nums = [int(n) for n in re.findall(r"^## L-(\d+)", text, re.M)]
    lid = f"L-{(max(nums) + 1 if nums else 1):03d}"
    entry = (
        f"\n## {lid} · {title}\n\n"
        f"- status: {status}\n- scope: {scope}\n- source: {source} ({iso()[:10]})\n"
        f"- rule: {rule}\n- enforced-by: {enforced_by}\n"
    )
    path.write_text(text.rstrip("\n") + "\n" + entry)
    row = find(load(), pr) if pr else None
    if row:
        fields = {"lesson": lid}
        if row.get("status") == "closed" and row.get("closed_at"):
            fields["lesson_closed_at"] = row["closed_at"]
        update_fields(pr, **fields)
    return lid
