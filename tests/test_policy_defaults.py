import base64
import pathlib
import sys
import unittest
from unittest.mock import patch

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from support import setup_module
from factory.oss import policy, records
from factory.util import CommandError


def setUpModule():
    setup_module(unittest)


class CommunityDefaults(unittest.TestCase):
    def setUp(self):
        self.files = {"example/project": {}, "example/.github": {}}
        self.private = False
        self.calls = []

    def lookup(self, *args):
        endpoint = args[1]
        self.calls.append(endpoint)
        repo, separator, path = endpoint.removeprefix("repos/").partition("/contents/")
        if not separator:
            return {"default_branch": "main", "stargazers_count": 1, "archived": False,
                    "private": self.private if repo.endswith("/.github") else False}
        files = self.files[repo]
        if path in files:
            return {"encoding": "base64", "content": base64.b64encode(files[path].encode()).decode()}
        prefix = path.rstrip("/") + "/" if path else ""
        entries = {}
        for name in files:
            if name.startswith(prefix):
                child, _, rest = name[len(prefix):].partition("/")
                entries[child] = {"name": child, "path": prefix + child, "type": "dir" if rest else "file"}
        if entries or not path:
            return list(entries.values())
        raise CommandError("HTTP 404: Not Found")

    def run_policy(self):
        with patch.object(policy, "gh_json", side_effect=self.lookup):
            return policy.run("example/project")

    def test_shared_contribution_rules_include_first_hand_source_paths(self):
        self.files["example/.github"]["CONTRIBUTING.md"] = "Discuss the issue before starting work.\nAdd tests.\n"
        result = self.run_policy()
        source = "https://github.com/example/.github/blob/main/CONTRIBUTING.md"
        self.assertIn(source, result["files"])
        self.assertTrue(result["flags"]["claim_first"][0].startswith(source + ":1:"))
        self.assertIn("tests_required", result["flags"])

    def test_automation_ban_is_found_in_each_supported_policy_surface(self):
        for path in ("CONTRIBUTING.md", "AI_POLICY.md", "CODE_OF_CONDUCT.md", ".github/PULL_REQUEST_TEMPLATE.md"):
            for repo in ("example/project", "example/.github"):
                with self.subTest(path=path, repo=repo):
                    self.files = {"example/project": {}, "example/.github": {}}
                    self.files[repo][path] = "We do not accept AI-generated contributions."
                    result = self.run_policy()
                    found = policy.blockers(result)
                    self.assertTrue(found)
                    self.assertIn(path + ":1:", found[0])
                    self.assertIn("We do not accept AI-generated contributions.", found[0])

    def test_shared_ai_policy_is_not_hidden_by_local_contribution_guide(self):
        self.files["example/project"]["CONTRIBUTING.md"] = "Understand your code and add tests."
        self.files["example/.github"]["AI_POLICY.md"] = "AI-assisted contributions need prior approval."
        self.assertTrue(policy.blockers(self.run_policy()))

    def test_neutral_ai_policy_and_understanding_do_not_block(self):
        self.files["example/project"]["CONTRIBUTING.md"] = (
            "AI-assisted code is welcome. You must understand every line of code you submit.")
        self.assertEqual(policy.blockers(self.run_policy()), [])

    def test_policy_regressions_also_hold_in_qualify(self):
        import contextlib
        import io
        from factory import cli
        from factory.oss import qualify

        cases = (
            ("We reject contributions generated by AI.", True),
            ("AI-generated contributions must be reviewed by a human before submission.", True),
            ("- [ ] No part of this contribution was generated by AI.", True),
            ("- [ ] I never used AI to prepare this contribution.", True),
            ("PR descriptions must be human-written and concise.", True),
            ("PR descriptions must be written by a human.", True),
            ("PR descriptions must be human-readable and concise.", False),
            ("AI tools may be used only if you understand and test the code.", False),
            ("AI tools may be used only if their use is disclosed in the PR.", False),
            ("AI assistance does not require prior approval.", False),
            ("We do not restrict AI assistance.", False),
            ("AI-assisted contributions are unrestricted.", False),
        )
        for text, blocked in cases:
            with self.subTest(text=text):
                self.files["example/project"] = {"CONTRIBUTING.md": text}
                result = self.run_policy()
                found = policy.blockers(result)
                self.assertEqual(bool(found), blocked, result)
                if blocked:
                    self.assertIn(text, found[0])
                # Each case is a different upstream text, so the saved repository record from the last case is dropped.
                records.path("example/project", "policy").unlink(missing_ok=True)
                with patch.object(policy, "gh_json", side_effect=self.lookup), \
                        patch.object(qualify, "run_keywords", return_value={"verdict": "ok", "skip": []}), \
                        contextlib.redirect_stdout(io.StringIO()):
                    self.assertEqual(cli.main(["qualify", "example/project", "--keyword", "parser"]), 2 if blocked else 0)

    def test_commit_attribution_rule_is_independent_of_source_path(self):
        for repo in self.files:
            for path in ("CONTRIBUTING.md", "docs/CONTRIBUTING.md"):
                with self.subTest(repo=repo, path=path):
                    self.files = {"example/project": {}, "example/.github": {}}
                    self.files[repo][path] = "Do not include AI attribution in commits."
                    self.assertEqual(policy.blockers(self.run_policy()), [])
        self.files["example/project"]["docs/CONTRIBUTING.md"] = "Do not include AI attribution in PR descriptions."
        self.assertTrue(policy.blockers(self.run_policy()))

    def test_shared_disclosure_format_is_extracted(self):
        self.files["example/.github"][".github/PULL_REQUEST_TEMPLATE.md"] = "- [ ] I used AI assistance."
        result = self.run_policy()
        self.assertEqual(policy.blockers(result), [])
        self.assertEqual(result["disclosure_formats"][0]["kind"], "checkbox")
        self.assertIn("example/.github/blob/main", result["disclosure_formats"][0]["source"])

    def test_policy_access_failure_does_not_turn_into_permission_to_submit(self):
        self.files["example/project"]["AI_POLICY.md"] = "Pull requests must not be generated by AI."
        lookup = self.lookup
        for denied in ("repos/example/project/contents/AI_POLICY.md", "repos/example/project/contents/"):
            def forbidden(*args, denied=denied):
                if args[1] == denied:
                    raise CommandError("HTTP 403: Forbidden")
                return lookup(*args)
            with self.subTest(denied=denied), patch.object(policy, "gh_json", side_effect=forbidden), \
                    self.assertRaises(CommandError):
                policy.run("example/project")

    def test_one_run_lists_folders_once_and_reads_only_files_that_exist(self):
        self.files["example/project"].update({"CONTRIBUTING.md": "Add tests.", ".github/workflows/ci.yml": "on: push"})
        self.run_policy()
        project = [call for call in self.calls if call.startswith("repos/example/project/contents/")]
        self.assertEqual(len(project), len(set(project)), "no GitHub path is read twice in one run")
        self.assertIn("repos/example/project/contents/CONTRIBUTING.md", project)
        probed = {"repos/example/project/contents/" + name for name in policy.FILES}
        self.assertEqual(probed & set(project), {"repos/example/project/contents/CONTRIBUTING.md"})
        self.assertLess(len(project), len(policy.FILES) // 2)

    def test_a_listing_at_the_api_limit_falls_back_to_probing_every_name(self):
        self.files["example/project"]["AGENTS.md"] = "We do not accept AI-generated contributions."
        lookup = self.lookup

        def truncated(*args):
            if args[1] == "repos/example/project/contents/":
                return [{"name": f"f{n}", "path": f"f{n}", "type": "file"} for n in range(policy.LISTING_LIMIT)]
            return lookup(*args)

        with patch.object(policy, "gh_json", side_effect=truncated):
            result = policy.run("example/project")
        self.assertIn("AGENTS.md", result["files"])
        self.assertTrue(policy.blockers(result))

    def test_an_unlistable_root_falls_back_to_probing_every_name(self):
        lookup = self.lookup
        def no_root(*args):
            if args[1] == "repos/example/project/contents/":
                raise CommandError("HTTP 404: Not Found")
            return lookup(*args)
        self.files["example/project"]["AI_POLICY.md"] = "We do not accept AI-generated contributions."
        with patch.object(policy, "gh_json", side_effect=no_root):
            result = policy.run("example/project")
        self.assertIn("AI_POLICY.md", result["files"])
        self.assertTrue(policy.blockers(result))

    def test_local_file_overrides_only_its_own_family(self):
        self.files["example/project"]["docs/CONTRIBUTING.md"] = "Local contribution guide."
        self.files["example/.github"].update({"CONTRIBUTING.md": "Discuss the issue before starting work.",
                                           "SECURITY.md": "Add security tests."})
        result = self.run_policy()
        self.assertNotIn("claim_first", result["flags"])
        self.assertIn("tests_required", result["flags"])
        self.assertNotIn("repos/example/.github/contents/CONTRIBUTING.md", self.calls)

    def test_shared_folder_precedence_and_lowercase_names(self):
        self.files["example/.github"].update({".github/contributing.md": "Add tests.",
                                           "CONTRIBUTING.md": "Discuss the issue before starting work.",
                                           "docs/CONTRIBUTING.md": "Sign the CLA."})
        flags = self.run_policy()["flags"]
        self.assertEqual(set(flags), {"tests_required"})

    def test_local_health_file_outside_the_legacy_probe_list_is_still_read(self):
        self.files["example/project"][".github/CONTRIBUTING.rst"] = "Add tests."
        result = self.run_policy()
        self.assertIn(".github/CONTRIBUTING.rst", result["files"])
        self.assertIn("tests_required", result["flags"])

    def test_missing_shared_repository_keeps_local_rules(self):
        self.files["example/project"]["CONTRIBUTING.md"] = "Add tests."
        lookup = self.lookup
        def missing(*args):
            if args[1] == "repos/example/.github":
                raise CommandError("HTTP 404: Not Found")
            return lookup(*args)
        with patch.object(policy, "gh_json", side_effect=missing):
            self.assertIn("tests_required", policy.run("example/project")["flags"])

    def test_private_shared_repository_is_not_inherited(self):
        self.private = True
        self.files["example/.github"]["CONTRIBUTING.md"] = "Add tests."
        self.assertEqual(self.run_policy()["files"], {})
        self.assertFalse(any("example/.github/contents" in call for call in self.calls))

    def test_agent_instructions_workflows_and_license_are_not_inherited(self):
        self.files["example/.github"].update({name: "Add tests. Sign the CLA." for name in
                                            ("AGENTS.md", "CLAUDE.md", "LICENSE.md", ".github/workflows/pr.yml")})
        result = self.run_policy()
        self.assertEqual(result["files"], {})
        self.assertEqual(result["flags"], {})

    def test_issue_forms_inherit_but_local_config_overrides_the_whole_folder(self):
        self.files["example/.github"][".github/ISSUE_TEMPLATE/bug.yml"] = (
            "body:\n  - type: input\n    id: repro\n    attributes:\n      label: Reproduction\n"
            "    validations:\n      required: true\n")
        self.assertIn("repro_required", self.run_policy()["flags"])
        self.files["example/project"][".github/ISSUE_TEMPLATE/config.yml"] = "blank_issues_enabled: true\n"
        self.assertNotIn("repro_required", self.run_policy()["flags"])

    def test_readme_in_issue_folder_does_not_suppress_shared_forms(self):
        self.files["example/.github"][".github/ISSUE_TEMPLATE/bug.yml"] = (
            "name: Bug report\ndescription: Report a reproducible bug\nbody:\n"
            "  - type: input\n    attributes:\n      label: Reproduction\n"
            "    validations:\n      required: true\n")
        self.files["example/project"][".github/ISSUE_TEMPLATE/README.md"] = "# Template authoring notes\n"
        self.assertIn("repro_required", self.run_policy()["flags"])

    def test_unverified_issue_templates_cannot_silently_suppress_defaults(self):
        self.files["example/.github"][".github/ISSUE_TEMPLATE/bug.yml"] = "Shared issue requirements."
        for name, text in (
            ("broken.yml", "name: ab\ndescription: Not a valid template name\nbody: []\n"),
            ("bug.yml", "name: Bug report\ndescription: Report a bug\nbody: *fields\n"),
            ("bug.md", "---\nname: Bug report\nabout: Report a bug\n---\nDescribe the bug.\n"),
            ("config.yml", "blank_issues_enabled: invalid\n"),
            ("config.yml", "blank_issues_enabled: true#not-a-comment\n"),
        ):
            with self.subTest(name=name):
                self.files["example/project"] = {".github/ISSUE_TEMPLATE/" + name: text}
                with self.assertRaisesRegex(ValueError, "issue-template override.*" + name):
                    self.run_policy()

    def test_simple_local_issue_config_overrides_even_with_unverified_forms(self):
        self.files["example/.github"][".github/ISSUE_TEMPLATE/bug.yml"] = "Add tests."
        self.files["example/project"] = {
            ".github/ISSUE_TEMPLATE/config.yml": "# Contact the team\nblank_issues_enabled: false # intentional\n",
            ".github/ISSUE_TEMPLATE/broken.yml": "name: ab\nbody: []\n",
        }
        self.assertNotIn("tests_required", self.run_policy()["flags"])

    def test_non_directory_health_locations_preserve_local_and_shared_rules(self):
        self.files["example/project"]["CONTRIBUTING.md"] = "Add tests."
        self.files["example/.github"]["SECURITY.md"] = "Sign the CLA."
        lookup = self.lookup
        for kind in ("file", "submodule", "symlink"):
            with self.subTest(kind=kind):
                def non_directory(*args):
                    if args[1] == "repos/example/project/contents/docs":
                        return {"type": kind, "name": "docs", "path": "docs", "sha": "a" * 40}
                    return lookup(*args)
                with patch.object(policy, "gh_json", side_effect=non_directory):
                    flags = policy.run("example/project")["flags"]
                self.assertIn("tests_required", flags)
                self.assertIn("cla", flags)

    def test_malformed_directory_responses_and_access_errors_still_fail(self):
        lookup = self.lookup
        for response in ({"unexpected": True}, {"type": "file"}, "bad response"):
            with self.subTest(response=response):
                def malformed(*args):
                    if args[1] == "repos/example/project/contents/docs":
                        return response
                    return lookup(*args)
                with patch.object(policy, "gh_json", side_effect=malformed), self.assertRaisesRegex(ValueError, "directory listing"):
                    policy.run("example/project")
        for code in (401, 403, 503):
            with self.subTest(code=code):
                def unavailable(*args):
                    if args[1] == "repos/example/project/contents/docs":
                        raise CommandError(f"HTTP {code}: unavailable")
                    return lookup(*args)
                with patch.object(policy, "gh_json", side_effect=unavailable), self.assertRaisesRegex(CommandError, str(code)):
                    policy.run("example/project")

    def test_local_single_or_multiple_pr_templates_block_shared_templates(self):
        self.files["example/.github"][".github/PULL_REQUEST_TEMPLATE/fix.md"] = "Add tests."
        self.assertIn("tests_required", self.run_policy()["flags"])
        for path in (".github/pull_request_template.md", "docs/PULL_REQUEST_TEMPLATE/fix.md"):
            with self.subTest(path=path):
                self.files["example/project"] = {path: "Local template."}
                self.assertNotIn("tests_required", self.run_policy()["flags"])

    def test_unavailable_shared_metadata_is_not_silently_treated_as_no_rules(self):
        lookup = self.lookup
        def unavailable(*args):
            if args[1] == "repos/example/.github":
                raise CommandError("HTTP 503: service unavailable")
            return lookup(*args)
        with patch.object(policy, "gh_json", side_effect=unavailable), self.assertRaisesRegex(CommandError, "503"):
            policy.run("example/project")
