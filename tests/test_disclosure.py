def rules(text, path="CONTRIBUTING.md"):
    flags, formats = policy.automation_rules({path: text})
    return {"flags": flags, "disclosure_formats": formats}


class AutomationRules(unittest.TestCase):
    def test_bans_and_restrictions_preserve_the_rule_and_source(self):
        cases = (
            "We do not accept AI-generated contributions.",
            "No AI-assisted pull requests.",
            "AI-assisted contributions are not allowed.",
            "AI-generated contributions require prior approval from a maintainer.",
            "Use of AI tools is restricted to documentation.",
            "AI tools may only be used for tests.",
            "We discourage AI-assisted contributions.",
            "AI contributions need explicit permission.",
            "We reject contributions generated by AI.",
            "AI-generated contributions are not currently accepted.",
            "We do not restrict AI assistance, but prior approval is required for AI contributions.",
            "We decline contributions believed to include or derive from AI generated content.",
            "The project requires that contributors refrain from using AI content generators.",
            "We refuse code produced by AI tools.",
            "AI-generated contributions must be reviewed by a human before submission.",
            "- [ ] No part of this contribution was generated by AI.",
            "- [ ] I never used AI to prepare this contribution.",
            "- [ ] This PR does not contain AI-generated code.",
            "- [ ] AI was not used to prepare this change.",
        )
        for text in cases:
            with self.subTest(text=text):
                found = policy.blockers(rules(text))
                self.assertTrue(found, text)
                self.assertIn("CONTRIBUTING.md:1:", found[0])
                self.assertIn(text, found[0])

    def test_wrapped_ban_and_heading_context(self):
        self.assertTrue(policy.blockers(rules("We do not accept\nAI-assisted contributions.")))
        self.assertTrue(policy.blockers(rules("## AI contributions\n\nPrior approval is required.")))
        self.assertTrue(policy.blockers(rules("## AI contributions\n\nWe do not accept these contributions.")))

    def test_understanding_testing_and_disclosure_are_not_restrictions(self):
        for text in ("You must understand every line of code you submit.",
                     "AI-assisted code is welcome. Contributors must understand and test their code.",
                     "You must review AI-generated code and take responsibility for it.",
                     "Disclose AI usage in your PR.", "Add a regression test.",
                     "AI-generated contributions are not prohibited.",
                     "We do not prohibit AI assistance.",
                     "We do not reject contributions generated by AI.",
                     "We never decline AI contributions.",
                     "We do not restrict AI assistance.",
                     "There are no restrictions on AI assistance.",
                     "AI-assisted contributions are unrestricted.",
                     "AI assistance does not require prior approval.",
                     "AI contributions do not require prior approval.",
                     "AI tools may be used only if you understand and test the code.",
                     "AI tools may be used only if their use is disclosed in the PR.",
                     "## AI is welcome\n\nThis section explains why we allow AI tools.",
                     "Do not include AI attribution in commits."):
            with self.subTest(text=text):
                self.assertEqual(policy.blockers(rules(text)), [])


class Body(unittest.TestCase):
    def setUp(self):
        mocker = patch.dict(CONFIG, public=PORTFOLIO)
        mocker.start()
        self.addCleanup(mocker.stop)

    def render(self, body="Fixes #7\n", source="", path="CONTRIBUTING.md", at=DATE):
        return disclosure.new_pr_body(body, rules(source, path), at=at)

    def test_default_is_automatic_idempotent_and_honest(self):
        body = self.render()
        self.assertEqual(body.count(disclosure.default_line()), 1)
        self.assertEqual(self.render(body), body)
        self.assertIn("https://github.com/" + PORTFOLIO["repository"], body)
        self.assertNotIn("human review", body.lower())
        self.assertEqual(slop.prose_findings("pr.md", body), ([], []))

    def test_start_date_boundary(self):
        self.assertEqual(self.render(at=DATE - dt.timedelta(days=1)), "Fixes #7\n")
        self.assertIn(disclosure.default_line(), self.render(at=DATE))

    def test_checkbox_is_checked_in_place_without_default_footer(self):
        source = "- [ ] I used AI assistance for this contribution."
        body = self.render("Fixes #7\n\n" + source + "\n", source, ".github/PULL_REQUEST_TEMPLATE.md")
        self.assertIn("- [x] I used AI assistance", body)
        self.assertEqual(body.count("I used AI"), 1)
        self.assertNotIn("Prepared by", body)
        self.assertEqual(self.render(body, source, ".github/PULL_REQUEST_TEMPLATE.md"), body)

    def test_required_section_stays_in_place(self):
        source = "## Summary\n\n## AI usage\n\n## Tests\n"
        body = self.render("## Summary\nFixes #7\n\n## AI usage\n\n## Tests\nTest passed.\n",
                           source, ".github/pull_request_template.md")
        self.assertEqual(body.count("## AI usage"), 1)
        self.assertLess(body.index(disclosure.default_line()), body.index("## Tests"))
        self.assertEqual(self.render(body, source, ".github/pull_request_template.md"), body)

    def test_prescribed_final_line_is_literal_and_final(self):
        source = "The PR body's last line must be exactly `_generated with AI_`."
        body = self.render(source=source)
        self.assertTrue(body.endswith("_generated with AI_\n"))
        self.assertNotIn("Prepared by", body)
        self.assertEqual(self.render(body, source), body)

    def test_unsupported_format_and_restrictions_refuse_instead_of_guessing(self):
        for source in ("No AI-generated contributions.",
                       "Disclose AI with the following format: <model>, <version>, <prompts>."):
            with self.subTest(source=source), self.assertRaises(ValueError):
                self.render(source=source)

    def test_human_only_checkbox_is_never_checked_by_the_factory(self):
        source = "- [ ] This PR does not contain AI-generated code."
        with self.assertRaises(ValueError):
            self.render(source=source, path=".github/PULL_REQUEST_TEMPLATE.md")

    def test_format_cannot_claim_human_review(self):
        source = "- [ ] I used AI and personally reviewed every line."
        with self.assertRaisesRegex(ValueError, "human attestation"):
            self.render(source=source, path=".github/PULL_REQUEST_TEMPLATE.md")

    def test_conflicting_literal_footers_require_policy_resolution(self):
        source = "The final line must be `AI used` or `AI assisted`."
        with self.assertRaisesRegex(ValueError, "conflicting"):
            self.render(source=source)

    def test_each_required_rule_needs_its_own_supported_format(self):
        for source in ("CONTRIBUTING.md", "https://github.com/example/.github/blob/main/AI_POLICY.md"):
            for template in ("## AI disclosure", "- [ ] I used AI assistance for this contribution."):
                with self.subTest(source=source, template=template):
                    required = "Disclose AI usage with the following format: <model>, <version>, <prompts>."
                    flags, formats = policy.automation_rules({source: required,
                        ".github/PULL_REQUEST_TEMPLATE.md": template})
                    with self.assertRaisesRegex(ValueError, "unsupported disclosure format") as raised:
                        disclosure.new_pr_body("Fixes #7\n", {"flags": flags, "disclosure_formats": formats}, at=DATE)
                    self.assertIn(required, str(raised.exception))

    def test_section_details_and_tool_trailers_remain_unresolved(self):
        for template in ("## AI disclosure\n\nSpecify the model, version, and prompts used.",
                         "## AI disclosure\nSpecify the model, version, and prompts used.",
                         "Disclose AI usage by adding an `Assisted-by: <tool>` trailer."):
            with self.subTest(template=template), self.assertRaisesRegex(ValueError, "unsupported disclosure format"):
                self.render(source=template, path=".github/PULL_REQUEST_TEMPLATE.md")

    def test_unknown_checkbox_assertions_never_become_claims(self):
        templates = (
            "Check the tool you used\n\n- [ ] I used Claude to prepare this contribution.\n"
            "- [ ] I used Copilot to prepare this contribution.",
            "- [ ] I used AI only to write tests.",
            "- [ ] All code was generated by AI.",
        )
        for template in templates:
            with self.subTest(template=template), self.assertRaisesRegex(ValueError, "unsupported.*attestation|automation policy"):
                # Tool names alone are not evidence of which parts of a change they produced.
                scanned = rules(template, ".github/PULL_REQUEST_TEMPLATE.md")
                scanned["tool_provenance"] = ["Claude"]
                disclosure.new_pr_body("Fixes #7\n", scanned, at=DATE)

    def test_negative_checkbox_attestations_refuse(self):
        for source in ("- [ ] No part of this contribution was generated by AI.",
                       "- [ ] I never used AI to prepare this contribution."):
            with self.subTest(source=source), self.assertRaises(ValueError):
                self.render(source=source, path=".github/PULL_REQUEST_TEMPLATE.md")

    def test_forbidden_example_is_not_a_literal_disclosure(self):
        source = 'Disclose the AI tool in this section; do not just write "AI used".'
        scanned = rules(source)
        self.assertNotIn("AI used", [row["text"] for row in scanned["disclosure_formats"]])
        with self.assertRaisesRegex(ValueError, "unsupported disclosure format"):
            self.render(source=source)

    def test_explanatory_section_does_not_require_a_format(self):
        source = "## AI is welcome\n\nThis section explains why we allow AI tools."
        self.assertEqual(self.render(source=source), self.render())
        self.assertEqual(self.render(source=source, path=".github/PULL_REQUEST_TEMPLATE.md"), self.render())
        explanation = ("## AI is welcome\n\nI include this section to be transparent about the project's usage "
                       "of AI for people who may disagree with it.")
        self.assertEqual(self.render(source=explanation), self.render())

    def test_every_supported_format_keeps_the_factory_link(self):
        for source in ("- [ ] I used AI assistance for this contribution.",
                       "The final line must be exactly `_generated with AI_`."):
            with self.subTest(source=source):
                body = self.render(source=source, path=".github/PULL_REQUEST_TEMPLATE.md")
                self.assertIn("https://github.com/" + PORTFOLIO["repository"], body)
                self.assertEqual(self.render(body, source, ".github/PULL_REQUEST_TEMPLATE.md"), body)

    def test_filler_and_commit_trailers_remain_failures(self):
        self.assertTrue(slop.prose_findings("pr.md", "A comprehensive, robust, seamless solution")[1])
        self.assertTrue(slop.prose_findings("commit abc", "Generated with AI")[0])
        self.assertTrue(slop.prose_findings("commit abc", "Co-authored-by: AI Copilot")[0])


class Profile(unittest.TestCase):
    def test_header_uses_config_deduplicates_merges_and_preserves_groups(self):
        rows = [{"repo": "upstream/parser", "number": 7, "status": "merged"}] * 2
        rows += [{"repo": "owner/tool", "number": 1, "status": "merged"},
                 {"repo": "upstream/parser", "number": 8, "status": "submitted"}]
        groups = {"groups": [{"title": "Parsers", "repos": [{"repo": "upstream/parser", "blurb": "Keep results"}]}]}
        with patch.dict(CONFIG, public=PORTFOLIO):
            body = profile_readme.render_readme("# Work\n\nHand-maintained projects.\n", rows, groups, "owner")
            again = profile_readme.render_readme(body, rows, groups, "owner")
        self.assertEqual(body, again)
        self.assertTrue(body.startswith(profile_readme.PORTFOLIO_START))
        self.assertIn("This account is automated", body)
        self.assertIn("**1 merged upstream pull requests**", body)
        self.assertIn(PORTFOLIO["dashboard_url"], body)
        self.assertIn("https://github.com/" + PORTFOLIO["repository"], body)
        self.assertIn("**Parsers**", body)
        self.assertIn("Hand-maintained projects.", body)


